import type { ReactNode } from "react";
import { cn } from "@/lib/cn";

export type CardVariant =
  | "cell"
  | "framed"
  | "elevated"
  | "bordered-accent"
  | "plain";

interface CardProps {
  children: ReactNode;
  /**
   * cell            — ячейка табличной сетки: границы рисует родитель, у карточки их нет.
   * framed          — КАРТОЧКА ПО УМОЛЧАНИЮ. Как она выглядит, решает пресет
   *                   тарифа: в «Экономе» это hairline-рамка на фоне своей
   *                   секции без тени, в «Стандарте» — собственная поверхность
   *                   с тенью и крупным радиусом, в «Premium» — акцентная рамка.
   *                   Именно поэтому секции ставят framed и не выбирают
   *                   глубину руками.
   * elevated        — явно поднятая карточка независимо от пресета: собственная
   *                   поверхность + тень. Ставится там, где подъём нужен по
   *                   смыслу, а не по тарифу (виджет hero, форма в контейнере).
   * bordered-accent — та же поверхность, но вместо тени акцентная рамка.
   * plain           — только контент, без отступов и оформления.
   */
  variant?: CardVariant;
  /**
   * Подъём карточки при наведении. Включать только там, где карточка
   * целиком кликабельна или ведёт себя как интерактивный объект —
   * cursor-pointer в наборе, и на статичном блоке он врёт пользователю.
   * Для «живой, но не кликабельной» карточки ничего включать не нужно:
   * в «Стандарте» реакция на курсор уже есть у любой карточки (--card-lift),
   * в «Экономе» её нет и не должно быть.
   */
  hoverEffect?: boolean;
  /**
   * Внутренние отступы карточки. Выключаются там, где содержимое обязано
   * доходить до края оболочки: панель с медиа во всю ширину, полоса
   * оправы браузера. Это НЕ способ подобрать отступ на глаз — своих
   * значений паддинга у карточки два (p-7 / md:p-9), и других быть не
   * должно; ручка ровно на «есть/нет».
   *
   * Отдельным пропом, а не `className="p-0"`: обе утилиты — padding, и
   * какая победит, решает порядок в собранном CSS, а не порядок в
   * строке класса.
   */
  padded?: boolean;
  className?: string;
}

/**
 * Ни одного значения тени, радиуса и цвета фона в этом файле: всё живёт
 * в классах .ui-card* (app/globals.css) и токенах --card-* / --radius-card
 * (theme/tokens.css). Так один и тот же компонент рендерит и плоскую базу,
 * и «дорогой» Стандарт — разница приезжает из data-preset на <html>.
 *
 * Если сюда захочется дописать утилиту тени или радиуса прямо в
 * className — почти наверняка нужен новый токен в блоке «РУЧКИ
 * ПРЕСЕТА», а не хардкод: хардкод ломает сразу оба тарифа (один
 * получает лишнюю глубину, другой — недостающую).
 */
const variants: Record<CardVariant, string> = {
  cell: "",
  framed: "ui-card border",
  elevated: "ui-card ui-card--elevated border",
  "bordered-accent": "ui-card ui-card--accent border",
  plain: "",
};

export function Card({
  children,
  variant = "cell",
  hoverEffect = false,
  padded = true,
  className,
}: CardProps) {
  return (
    <div
      className={cn(
        variants[variant],
        padded && variant !== "plain" && "p-7 md:p-9",
        hoverEffect && "ui-card--interactive cursor-pointer",
        className,
      )}
    >
      {children}
    </div>
  );
}

export default Card;
